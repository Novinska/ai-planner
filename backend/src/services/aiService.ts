export const aiService = {
  analyzePrompt: async (
    userPrompt: string,
    currentSchedule: any[],
    retries = 3,
    delay = 1500,
  ) => {
    for (let attempt = 1; attempt <= retries; attempt++) {
      try {
        const model = ai.getGenerativeModel({
          model: "gemini-2.5-flash",
          systemInstruction,
        });

        const fullContent = `
Поточний розклад користувача: ${JSON.stringify(currentSchedule)}
Новий запит користувача: "${userPrompt}"
        `;

        const result = await model.generateContent({
          contents: [{ role: "user", parts: [{ text: fullContent }] }],
          generationConfig: {
            responseMimeType: "application/json",
            responseSchema: planSchema as any,
            temperature: 0.3,
          },
        });

        const text = result.response.text();
        if (!text) throw new Error("Gemini не повернув text");

        console.log("Розумне перепланування:", text);
        return JSON.parse(text);
      } catch (error: any) {
        if (
          (error.status === 503 || error.status === 429) &&
          attempt < retries
        ) {
          console.warn(
            `[Gemini API] Сервер перевантажено. Спроба ${attempt} з ${retries}. Чекаємо ${delay}мс...`,
          );
          await new Promise((resolve) => setTimeout(resolve, delay));
          continue;
        }

        console.error("Остаточна помилка при запиті до Gemini API:", error);
        throw new Error(
          "Сервер ШІ тимчасово перевантажений. Спробуйте ще раз за хвилину.",
        );
      }
    }
  },
};
